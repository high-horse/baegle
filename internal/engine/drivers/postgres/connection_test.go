func TestReadOnlyStartupParameter(t *testing.T) {
	for _, readOnly := range []bool{true, false} {
		conn := New(entities.ConnectionConfig{User: "reader", Database: "data", ReadOnly: readOnly}, transports.NewDirect("localhost", 5432))
		cfg, err := pgx.ParseConfig(conn.dsn())
		if err != nil {
			t.Fatal(err)
		}
		if got := cfg.RuntimeParams["default_transaction_read_only"]; (got == "on") != readOnly {
			t.Fatalf("read-only=%v: startup parameter %q", readOnly, got)
		}
	}
}

func TestLivePostgresReadOnlySessions(t *testing.T) {
	dsn := os.Getenv("DB_VIEWER_READONLY_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set DB_VIEWER_READONLY_POSTGRES_DSN for live PostgreSQL validation")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	admin, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	name := fmt.Sprintf("baegle_readonly_%d", time.Now().UnixNano())
	if _, err := admin.ExecContext(ctx, "CREATE TABLE "+name+"(id integer)"); err != nil {
		t.Fatal(err)
	}
	defer func() {
		if _, err := admin.Exec("DROP TABLE " + name); err != nil {
			t.Error(err)
		}
	}()
	if _, err := admin.ExecContext(ctx, "INSERT INTO "+name+" VALUES(1)"); err != nil {
		t.Fatal(err)
	}
	// Apply the exact startup parameters generated by the app to the supplied
	// test endpoint, which may use a local Unix socket rather than TCP.
	c := New(entities.ConnectionConfig{ReadOnly: true}, transports.NewDirect("localhost", 5432))
	startup, err := pgx.ParseConfig(c.dsn())
	if err != nil {
		t.Fatal(err)
	}
	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.RuntimeParams["default_transaction_read_only"] = startup.RuntimeParams["default_transaction_read_only"]
	readDB := stdlib.OpenDB(*cfg)
	defer readDB.Close()
	readDB.SetMaxOpenConns(2)
	// Hold both connections so this verifies initialization on every pooled session.
	for range 2 {
		session, err := readDB.Conn(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer session.Close()
		var count int
		if err := session.QueryRowContext(ctx, "SELECT count(*) FROM "+name).Scan(&count); err != nil || count != 1 {
			t.Fatalf("read: %d %v", count, err)
		}
		for _, query := range []string{"INSERT INTO " + name + " VALUES(2)", "WITH changed AS (DELETE FROM " + name + " RETURNING *) SELECT * FROM changed", "CREATE TABLE " + name + "_extra(id integer)"} {
			if _, err := session.ExecContext(ctx, query); err == nil {
				t.Errorf("native read-only session accepted %s", query)
			}
		}
	}
}
